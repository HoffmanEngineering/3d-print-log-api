namespace PrintLogApi.Achievements;

/// <summary>
/// Normalizes the slicer name a plugin posts with its settings (<c>CuraSetting.Slicer</c>) into the
/// key stored on <c>Print.Slicer</c>. Keyed on the actual wire values: each Slic3r uploader
/// parser's <c>SlicerName</c>, and for a connector's settings (<c>PrintSlicerSettingsService</c>)
/// either that same name from the parser library or, when the library does not recognize the
/// header, the slicer Moonraker's metadata names. The Cura plugin sends no name at all.
/// </summary>
public static class SlicerNames
{
    public const string Cura = "cura";
    public const string PrusaSlicer = "prusaslicer";
    public const string OrcaSlicer = "orcaslicer";
    public const string BambuStudio = "bambustudio";
    public const string Anycubic = "anycubic";
    public const string FLSun = "flsun";
    public const string Other = "other";

    // Forks reach this map through a connector: the parser library has no marker for their headers,
    // so the name is Moonraker's metadata slicer, the text between "; generated by " and the
    // version (spellings taken from each fork's source). Through the Slic3r uploader the same
    // G-code posts one of the uploader's own names, usually "OrcaSlicer".
    //
    // These forks count as OrcaSlicer by the owner's decision (2026-10-15). SuperSlicer and
    // QIDISlicer are PrusaSlicer forks, deliberately counted as Orca too; moving them to
    // PrusaSlicer is a change to their two lines. Forks with their own key (Bambu Studio, Anycubic
    // Slicer Next, FLSun Slicer) keep it. One entry per name, so each fork can move on its own.
    private static readonly Dictionary<string, string> WireValues = new(StringComparer.OrdinalIgnoreCase)
    {
        ["PrusaSlicer"] = PrusaSlicer,
        ["OrcaSlicer"] = OrcaSlicer,

        // Snapmaker Orca writes "Snapmaker Orca 2.4.0"; the Snapmaker U1's own Moonraker reports
        // "SnapmakerOrca".
        ["SnapmakerOrca"] = OrcaSlicer,
        ["Snapmaker Orca"] = OrcaSlicer,
        ["ElegooSlicer"] = OrcaSlicer,
        ["Elegoo Slicer"] = OrcaSlicer,
        // Creality Print writes "Creality_Print V6.x" (its cloud build "Creality_Cloud_Slicer").
        ["Creality_Print"] = OrcaSlicer,
        ["Creality_Cloud_Slicer"] = OrcaSlicer,
        ["CrealityPrint"] = OrcaSlicer,
        ["Creality Print"] = OrcaSlicer,
        // QIDI Studio writes a Bambu-style "; QIDIStudio 02.x" with no "generated by", so stock
        // Moonraker reports "Unknown"; mapped for a Moonraker build that names it.
        ["QIDIStudio"] = OrcaSlicer,
        ["QIDI Studio"] = OrcaSlicer,
        // Orca-FlashForge writes its app name, "Flash Studio".
        ["Flash Studio"] = OrcaSlicer,

        // PrusaSlicer forks, counted as OrcaSlicer on purpose (see above).
        ["SuperSlicer"] = OrcaSlicer,
        ["QIDISlicer"] = OrcaSlicer,

        ["BambuStudioSlicer"] = BambuStudio,
        ["AnycubicSlicerNext"] = Anycubic,
        ["FLSunSlicer"] = FLSun,
    };

    /// <summary>The slicers that have a dedicated badge. FLSun and "other" have none.</summary>
    public static readonly IReadOnlySet<string> BadgeSlicers =
        new HashSet<string> { Cura, PrusaSlicer, OrcaSlicer, BambuStudio, Anycubic };

    /// <summary>
    /// Maps a wire value to its key. Null or empty means the Cura plugin; anything unrecognized is
    /// <see cref="Other"/>. Already-normalized keys map to themselves.
    /// </summary>
    public static string Normalize(string? wireValue)
    {
        if (string.IsNullOrWhiteSpace(wireValue))
        {
            return Cura;
        }

        var trimmed = wireValue.Trim();
        if (WireValues.TryGetValue(trimmed, out var key))
        {
            return key;
        }

        return trimmed.ToLowerInvariant() switch
        {
            Cura or PrusaSlicer or OrcaSlicer or BambuStudio or Anycubic or FLSun => trimmed.ToLowerInvariant(),
            _ => Other,
        };
    }
}
