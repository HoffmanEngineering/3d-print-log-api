    [Fact]
    public async Task RequestOverTheCap_WithoutAContentLength_Is413()
    {
        // A chunked body has no Content-Length, so only counting what is read catches it. The test
        // server buffers every request and adds the header, so this drives the reader directly.
        using var content = new MultipartFormDataContent
        {
            { new StringContent(Metadata()), "metadata" },
            { new ByteArrayContent(new byte[SlicerController.MaxRequestBytes]), "gcode", "upload.gcode.gz" },
        };
        var http = new DefaultHttpContext();
        http.Request.ContentType = content.Headers.ContentType!.ToString();
        http.Request.Body = await content.ReadAsStreamAsync(TestContext.Current.CancellationToken);
        Assert.Null(http.Request.ContentLength);

        var rejected = await Assert.ThrowsAsync<SlicerUploadRejectedException>(() => SlicerUploadReader.ReadAsync(
            http.Request, SlicerController.MaxRequestBytes, SlicerController.MaxMetadataBytes, TestContext.Current.CancellationToken));

        Assert.Equal(StatusCodes.Status413PayloadTooLarge, rejected.StatusCode);
    }

