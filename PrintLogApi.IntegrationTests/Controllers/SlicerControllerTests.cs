    [Fact]
    public async Task GzipBomb_Returns413_WithoutInflatingIt()
    {
        // 1 GiB of zeros is about a megabyte of gzip: well under the request cap.
        var bomb = GzipZeros(1L << 30);
        Assert.True(bomb.Length < SlicerController.MaxRequestBytes);

        var before = GC.GetTotalAllocatedBytes(precise: false);
        var response = await SendAsync(bomb, Metadata());
        var allocated = GC.GetTotalAllocatedBytes(precise: false) - before;

        await AssertStatusAsync(HttpStatusCode.RequestEntityTooLarge, response);
        // Process-wide, so other tests running in parallel count too; inflating the bomb would
        // allocate at least 2 GiB of chars on its own.
        Assert.True(allocated < 1L << 30, $"Allocated {allocated:N0} bytes.");
    }

