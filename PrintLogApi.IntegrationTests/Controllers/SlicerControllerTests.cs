    [Fact]
    public async Task Upload_StoresWhatTheLibraryProduces_AndTheUserCanClaimIt()
    {
        var gcode = FixtureText();

        var response = await SendAsync(Gzip(gcode), Metadata(outputName: @"C:\Prints\calibration_cube_final.gcode", models: CubeModels));

        await AssertStatusAsync(HttpStatusCode.OK, response);
        var created = (await response.Content.ReadFromJsonAsync<NewCuraSettingsDto>(TestContext.Current.CancellationToken))!;
        Assert.NotEqual(Guid.Empty, created.NewSettingId);

        using var stored = await ClaimAsync(created.NewSettingId);
        var root = stored.RootElement;
        Assert.Equal("OrcaSlicer", root.GetProperty("slicer").GetString());
        Assert.Equal("2.2.0-rc", root.GetProperty("curaVersion").GetString());
        Assert.Equal("orca-plugin/0.1.0", root.GetProperty("pluginVersion").GetString());

        var expected = SlicerGcodeParser.Parse(
            SlicerSettingsScrubber.ScrubText(gcode),
            new SlicerGcodeOptions("default", [new ModelBounds("Calibration Cube.stl", 100.2, 119.8, 100.2, 119.8, 20.0)], [])
            {
                OutputName = @"C:\Prints\calibration_cube_final.gcode",
            });
        using var expectedSettings = JsonDocument.Parse(expected.SettingsJson);
        var settings = root.GetProperty("settings");
        Assert.True(
            JsonElement.DeepEquals(expectedSettings.RootElement, settings),
            $"Stored settings differ from the library's.\nExpected: {expectedSettings.RootElement}\nActual: {settings}");

        // And the library's output is the uploader's: its own dry-run note for the same file.
        Assert.Equal(DryRunNote(), settings.GetProperty("note").GetString());
        Assert.Equal("calibration_cube_final.gcode", settings.GetProperty("file_name").GetString());
        Assert.Equal("Calibration Cube Final", settings.GetProperty("print_name").GetString());
        Assert.False(string.IsNullOrEmpty(settings.GetProperty("snapshot").GetString()));
    }

