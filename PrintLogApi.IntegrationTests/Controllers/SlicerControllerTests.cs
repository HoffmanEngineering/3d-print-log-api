    [Fact]
    public async Task Upload_CredentialsInTheTextAndInPresets_NeverReachTheStoredSettings()
    {
        var gcode = WithSecrets(FixtureText());
        var presets = new object[]
        {
            new
            {
                kind = "machine",
                name = "JGMaker R1",
                json = """{ "name": "JGMaker R1", "inherits": "MyMarlin 0.4 nozzle", "printhost_apikey": "SECRET-PRESET-KEY", "nested": { "print_host": "SECRET-PRESET-HOST" } }""",
            },
        };

        var response = await SendAsync(Gzip(gcode), Metadata(userPresets: presets));

        await AssertStatusAsync(HttpStatusCode.OK, response);
        var created = (await response.Content.ReadFromJsonAsync<NewCuraSettingsDto>(TestContext.Current.CancellationToken))!;

        // The raw column, not just what the GET serializes.
        var stored = await LoadAsync(created.NewSettingId);
        var raw = stored.Settings.GetRawText();
        Assert.DoesNotContain("SECRET", raw, StringComparison.Ordinal);

        // The key is listed (Orca says it changed) but its value is gone, so the scrub ran before
        // the parse rather than the secret simply not being rendered.
        var note = stored.Settings.GetProperty("note").GetString()!;
        Assert.Contains("printhost_apikey = (not in G-code)", note, StringComparison.Ordinal);
