    private static readonly string FixtureDirectory = Path.Combine(AppContext.BaseDirectory, "tests-fixtures");

    private static string FixtureText() =>
        System.IO.File.ReadAllText(Path.Combine(FixtureDirectory, "slicer-uploads", $"{OrcaCube}.gcode"), Encoding.UTF8);

    private static string DryRunNote() =>
