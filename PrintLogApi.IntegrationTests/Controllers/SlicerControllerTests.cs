    /// <summary>
    /// A host key and an API key the way Orca writes them, with the key also in
    /// <c>different_settings_to_system</c> so the note would list its value if it survived.
    /// </summary>
    private static string WithSecrets(string gcode) => gcode
        .Replace("; printhost_authorization_type = key", "; printhost_authorization_type = key\r\n; printhost_apikey = SECRET-TEXT-KEY\r\n; print_host = SECRET-TEXT-HOST", StringComparison.Ordinal)
        .Replace("; different_settings_to_system = post_process;", "; different_settings_to_system = post_process;printhost_apikey;", StringComparison.Ordinal);

    private static string Pad(string text, int length) =>
        text + "\n" + new string(' ', length - text.Length - 1);

    private static string Metadata(
        string? pluginVersion = "0.1.0",
        string? slicerVersion = "2.2.0-rc",
        string? outputName = "calibration_cube.gcode",
        string? template = "default",
        object[]? models = null,
        object[]? userPresets = null) =>
        JsonSerializer.Serialize(new
        {
            pluginVersion,
            slicerVersion,
            outputName,
            host = "File",
            template,
            models = models ?? [],
            userPresets = userPresets ?? [],
        });

    private static byte[] Gzip(string text)
    {
        using var output = new MemoryStream();
        using (var gzip = new GZipStream(output, CompressionLevel.Fastest, leaveOpen: true))
        {
            var bytes = Encoding.UTF8.GetBytes(text);
            gzip.Write(bytes);
        }

        return output.ToArray();
    }

    private static byte[] GzipZeros(long count)
    {
        using var output = new MemoryStream();
        using (var gzip = new GZipStream(output, CompressionLevel.SmallestSize, leaveOpen: true))
        {
            var chunk = new byte[1 << 20];
            for (long written = 0; written < count; written += chunk.Length)
            {
                gzip.Write(chunk);
            }
        }

        return output.ToArray();
    }

    private static ByteArrayContent GcodePart(byte[] gzip)
    {
        var part = new ByteArrayContent(gzip);
        part.Headers.ContentType = new MediaTypeHeaderValue("application/gzip");
        return part;
    }

    private async Task<HttpResponseMessage> SendAsync(byte[] gcode, string metadata)
    {
        using var content = new MultipartFormDataContent
        {
            { GcodePart(gcode), "gcode", "upload.gcode.gz" },
            { new StringContent(metadata, Encoding.UTF8, "application/json"), "metadata" },
        };

        return await _httpClient.PostAsync(Url, content, TestContext.Current.CancellationToken);
    }

    private static async Task AssertStatusAsync(HttpStatusCode expected, HttpResponseMessage response)
    {
        if (response.StatusCode != expected)
        {
            var body = await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken);
            Assert.Fail($"Expected {expected}, got {response.StatusCode}: {body}");
        }
    }

    private async Task<JsonDocument> ClaimAsync(Guid id)
    {
        var request = new HttpRequestMessage(HttpMethod.Get, $"/api/Cura/settings?id={id}");
        request.Headers.Add(TestAuthHandler.TestUserIdHeader, IntegrationTestSeeder.TestUserOAuthId);
        var response = await _httpClient.SendAsync(request, TestContext.Current.CancellationToken);
        await AssertStatusAsync(HttpStatusCode.OK, response);
        return JsonDocument.Parse(await response.Content.ReadAsStringAsync(TestContext.Current.CancellationToken));
    }

    private async Task<PrintLogApi.Models.CuraSetting> LoadAsync(Guid id)
    {
        using var scope = factory.Services.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<PrintLogContext>();
        return await context.CuraSettings.AsNoTracking().SingleAsync(c => c.Id == id, TestContext.Current.CancellationToken);
    }

